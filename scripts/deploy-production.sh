#!/usr/bin/env bash
# Run as the same OS user that owns the existing PM2 process.
# Usage: bash scripts/deploy-production.sh
# Optional: APP_DIR, BACKUP_ROOT, PM2_APP, DEPLOY_BRANCH, DEPLOY_REMOTE, HEALTH_URL.
# DATABASE_URL follows Next.js production env precedence (including shell overrides).
set -Eeuo pipefail
umask 077

main() {
  if [[ "${1:-}" == '--help' ]]; then
    echo 'Usage: bash scripts/deploy-production.sh'
    echo 'Optional variables: APP_DIR BACKUP_ROOT PM2_APP DEPLOY_BRANCH DEPLOY_REMOTE HEALTH_URL'
    echo 'Requires existing node_modules, production env, PostgreSQL client tools and PM2.'
    echo 'Stops the app during backup/deploy. On failure it stays stopped; no automatic database restore.'
    return 0
  fi

  APP_DIR="${APP_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
  cd "$APP_DIR"
  APP_DIR="$(pwd -P)"
  BACKUP_ROOT="${BACKUP_ROOT:-$HOME/backups/fims-deploy}"
  PM2_APP="${PM2_APP:-fims}"
  DEPLOY_BRANCH="${DEPLOY_BRANCH:-main}"
  DEPLOY_REMOTE="${DEPLOY_REMOTE:-origin}"
  HEALTH_URL="${HEALTH_URL:-http://127.0.0.1:3000/api/auth/session}"
  local stage='provjera preduslova' backup_dir='' runtime_env='' stopped=0 lock_owned=0
  local lock_dir="$APP_DIR/.git/fims-deploy.lock"

  cleanup() {
    local code=$?
    trap - EXIT
    if [[ -n "$runtime_env" ]]; then rm -f -- "$runtime_env"; fi
    if (( code != 0 )); then
      echo "GREŠKA: deploy zaustavljen — $stage." >&2
      echo "Backup: ${backup_dir:-još nije kreiran}. Baza se NE vraća automatski." >&2
      if (( stopped )); then
        pm2 stop "$PM2_APP" >/dev/null 2>&1 || true
        echo 'Aplikacija ostaje zaustavljena. Otklonite grešku prije ponovnog pokretanja.' >&2
      fi
    fi
    if (( lock_owned )); then rmdir "$lock_dir"; fi
    exit "$code"
  }
  trap cleanup EXIT
  trap 'exit 130' INT
  trap 'exit 143' TERM

  for command in git node npm pm2 pg_dump pg_restore tar curl mktemp; do
    command -v "$command" >/dev/null || { echo "Nedostaje alat: $command" >&2; exit 1; }
  done
  [[ -d .git && -f package-lock.json && -d node_modules/@next/env ]] || {
    echo 'Pokrenite u postojećem produkcijskom checkoutu s instaliranim zavisnostima.' >&2; exit 1;
  }
  mkdir "$lock_dir" || { echo 'Drugi deploy je aktivan ili je ostao deploy lock.' >&2; exit 1; }
  lock_owned=1
  [[ -z "$(git status --porcelain)" ]] || { echo 'Repozitorij ima lokalne izmjene. Sačuvajte ih prije deploya.' >&2; exit 1; }
  [[ "$(git branch --show-current)" == "$DEPLOY_BRANCH" ]] || { echo 'Pogrešna Git grana.' >&2; exit 1; }
  pm2 describe "$PM2_APP" >/dev/null
  node -e 'const [major, minor] = process.versions.node.split(".").map(Number); if (major < 20 || (major === 20 && minor < 9)) process.exit(1)'

  mkdir -p "$BACKUP_ROOT"
  BACKUP_ROOT="$(cd "$BACKUP_ROOT" && pwd -P)"
  case "$BACKUP_ROOT/" in "$APP_DIR/"*) echo 'Backup mora biti izvan direktorija aplikacije.' >&2; exit 1;; esac
  backup_dir="$(mktemp -d "$BACKUP_ROOT/deploy-$(date +%Y%m%d_%H%M%S)-XXXXXX")"
  runtime_env="$(mktemp "$backup_dir/.runtime-XXXXXX")"

  # Use the same env-file precedence as Next.js production, without sourcing .env as shell code.
  node - "$runtime_env" <<'NODE'
const fs = require('fs')
const path = require('path')
process.env.NODE_ENV = 'production'
require('@next/env').loadEnvConfig(process.cwd(), false, { info() {}, error() {} })
try {
  const database = process.env.DATABASE_URL
  if (!database) throw new Error('DATABASE_URL nije postavljen')
  const pg = new URL(database)
  if (!['postgres:', 'postgresql:'].includes(pg.protocol)) throw new Error('Očekuje se PostgreSQL DATABASE_URL')
  // Prisma-only options are not understood by libpq/pg_dump.
  for (const key of ['schema', 'connection_limit', 'pool_timeout', 'pgbouncer', 'statement_cache_size', 'socket_timeout']) pg.searchParams.delete(key)
  const password = decodeURIComponent(pg.password)
  pg.password = ''
  if (!pg.username || !pg.hostname || !pg.pathname.slice(1)) throw new Error('Nepotpuni podaci konekcije')
  const upload = path.resolve(process.env.UPLOAD_DIR || './public/uploads/certificates')
  if (!fs.existsSync(upload)) throw new Error('UPLOAD_DIR ne postoji; provjerite putanju certifikata')
  const quote = value => "'" + value.replace(/'/g, "'\\''") + "'"
  fs.writeFileSync(process.argv[2], Object.entries({ DATABASE_URL: database, DEPLOY_DATABASE_URL: pg.toString(), ...(password ? { PGPASSWORD: password } : {}), DEPLOY_UPLOAD_DIR: upload })
    .map(([key, value]) => `export ${key}=${quote(value)}`).join('\n') + '\n', { mode: 0o600 })
} catch (error) {
  console.error('Provjera produkcijskog okruženja nije uspjela. Provjerite DATABASE_URL i UPLOAD_DIR; detalji konekcije nisu ispisani.')
  process.exit(1)
}
NODE
  # Generated by the trusted loader above, not arbitrary shell from an env file.
  source "$runtime_env"
  rm -f "$runtime_env"
  runtime_env=''
  export NODE_ENV=production

  stage='zaustavljanje aplikacije'
  stopped=1
  pm2 stop "$PM2_APP"

  stage='backup aplikacije, konfiguracije i certifikata'
  echo "Backup aplikacije: $backup_dir"
  git rev-parse HEAD > "$backup_dir/previous-commit.txt"
  # Includes .env*, .git, PM2 configuration and existing build; dependencies can be reinstalled.
  tar --exclude='./node_modules' --exclude='./.next/cache' --exclude='./.git/fims-deploy.lock' \
    -czf "$backup_dir/application.tar.gz" -C "$APP_DIR" .
  tar -tzf "$backup_dir/application.tar.gz" > /dev/null
  # Separate archive also covers UPLOAD_DIR outside the repository.
  tar -czf "$backup_dir/uploads.tar.gz" -C "$DEPLOY_UPLOAD_DIR" .
  tar -tzf "$backup_dir/uploads.tar.gz" > /dev/null

  stage='backup produkcijske baze'
  echo 'Backup baze...'
  pg_dump --dbname="$DEPLOY_DATABASE_URL" --no-password --format=custom --file="$backup_dir/database.dump"
  test -s "$backup_dir/database.dump"
  pg_restore --list "$backup_dir/database.dump" > "$backup_dir/database-contents.txt"
  test -s "$backup_dir/database-contents.txt"
  echo 'Oba backupa uspješna. Počinje deploy.'

  stage='preuzimanje koda'
  git fetch "$DEPLOY_REMOTE" "$DEPLOY_BRANCH"
  local target_commit
  target_commit="$(git rev-parse FETCH_HEAD)"
  git merge --ff-only "$target_commit"
  printf '%s\n' "$target_commit" > "$backup_dir/deployed-commit.txt"

  stage='instalacija zavisnosti'
  npm ci --include=dev
  stage='migracije baze'
  ./node_modules/.bin/prisma migrate deploy
  ./node_modules/.bin/prisma migrate status
  stage='produkcijski build'
  npm run build

  unset DEPLOY_DATABASE_URL PGPASSWORD DEPLOY_UPLOAD_DIR
  stage='pokretanje aplikacije'
  pm2 restart "$PM2_APP" --update-env
  stage='provjera HTTP odgovora'
  local healthy=0
  for (( attempt=1; attempt<=30; attempt++ )); do
    if curl --fail --silent --output /dev/null --max-time 5 "$HEALTH_URL"; then healthy=1; break; fi
    sleep 2
  done
  (( healthy )) || { echo 'Aplikacija ne odgovara uspješno. Provjerite PM2 logove.' >&2; exit 1; }
  stopped=0
  echo "DEPLOY USPJEŠAN: $target_commit"
  echo "Backup sačuvan: $backup_dir"
  echo 'Provjerite prijavu korisnika, stari PDF, certifikate i kreiranje nove prijave.'
  cleanup
}

main "$@"
